/* Put the shared footer in place of the page's own <footer>, or before
   </body> on a page that had none. */
function applyFooter(html, block) {
  if (html.includes(FSTART)) {
    const a = html.indexOf(FSTART), z = html.indexOf(FEND, a);
    // A start marker without its end means a hand edit or a merge broke the
    // page; splicing anyway would paste the footer over the wrong text.
    if (z === -1) throw new Error('site-footer: start marker without an end marker');
    return html.slice(0, a) + block + html.slice(z + FEND.length);
  }
  const f = html.search(/<footer\b/i);
  if (f !== -1) {
    const start = html.lastIndexOf('\n', f) + 1;
    let end = elementEnd(html, f);
    // Swallow the "<!-- Footer -->" label above it, if any.
    const label = html.slice(0, start).match(/[ \t]*<!--\s*(=+\s*)?footer[^>]*-->\s*\n$/i);
    return html.slice(0, label ? start - label[0].length : start) + block + html.slice(end);
  }
  const body = html.lastIndexOf('</body>');
  return body === -1 ? html : html.slice(0, body) + block + '\n' + html.slice(body);
}

/* The end of the element that opens at `from` (same tag, nesting counted). */
function elementEnd(html, from) {
  const tag = html.slice(from + 1).match(/^[a-zA-Z0-9]+/)[0].toLowerCase();
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
  re.lastIndex = from;
  let depth = 0, m;
  while ((m = re.exec(html))) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return m.index + m[0].length;
  }
  throw new Error(`unclosed <${tag}> at ${from}`);
}

/* The old, per-page copies of the menu, removed on a page's first --write. */
const OLD = [
  /<div class="announcement-bar"[^>]*>/i,
  /<header\b[^>]*>/i,
  /<div class="drawer-overlay"[^>]*>/i,
  /<div class="mobile-drawer"[^>]*>/i,
];

/* Pages with the reviews block from tools/page-blocks.js show reviews there,
   once (owner, 2026-10-17: "do we need reviews on the page twice?"). */
let blockPages = null;
const BLOCK_PAGES = () => blockPages || (blockPages = new Set(Object.keys(require('./page-blocks').load().data.pages)));

function applyReviews(html, rel) {
  if (NO_REVIEWS.has(rel) || BLOCK_PAGES().has(rel)) {
    const a = html.indexOf(RS);
    if (a === -1) return html;
    const z = html.indexOf(RE, a);
    if (z === -1) throw new Error('review-strip: start marker without an end marker');
    const b = z + RE.length;
    html = html.slice(0, html.lastIndexOf('\n', a - 1) + 1) + html.slice(b).replace(/^\n/, '');
    if (!html.includes('id="jt-reviews"')) html = html.replace(new RegExp(`[ \\t]*${REVIEW_CSS_TAG.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}\\n`), '');
    return html;
  }
  if (html.includes(RS)) {
    const a = html.indexOf(RS), b = html.indexOf(RE, a) + RE.length;
    html = html.slice(0, a) + REVIEWS_BLOCK + html.slice(b);
  } else {
    const f = html.search(/<footer\b/i);
    if (f === -1) return html;
    const lineStart = html.lastIndexOf('\n', f) + 1;
    html = html.slice(0, lineStart) + REVIEWS_BLOCK + '\n' + html.slice(lineStart);
  }
  if (!html.includes(REVIEW_CSS_TAG)) html = html.replace('</head>', `  ${REVIEW_CSS_TAG}\n</head>`);
  return html;
}

function apply(html, block) {
  if (html.includes(START)) {
    const a = html.indexOf(START), b = html.indexOf(END, a) + END.length;
    html = html.slice(0, a) + block + html.slice(b);
  } else {
    let at = -1;
    for (const re of OLD) {
      const body = html.indexOf('<body');
      const m = re.exec(html.slice(body));
      if (!m) continue;
      const s = body + m.index;
      // Swallow the comment that labelled it, if any, and the line it sat on.
      let start = s;
      // Swallow the comments that labelled it ("<!-- Header -->"), if any.
      for (;;) {
        const c = html.slice(0, start).match(/[ \t]*<!--[^>]*-->\s*$/);
        if (!c || !/announcement|header|drawer/i.test(c[0])) break;
        start -= c[0].length;
      }
      const end = elementEnd(html, s);
      if (at === -1 || start < at) at = start;
      html = html.slice(0, start) + '\u0000NAV\u0000' + html.slice(end);
    }
    // Every removed piece became a placeholder; the first gets the menu.
    const first = html.indexOf('\u0000NAV\u0000');
    if (first === -1) {
      const m = html.match(/<body[^>]*>/i);
      html = html.replace(m[0], m[0] + '\n' + block);
    } else {
      html = html.slice(0, first) + block + html.slice(first + 5).split('\u0000NAV\u0000').join('');
    }
  }
  html = dropOldTicker(html);
  html = NAV_CSS.put(html);
  html = QUOTE_JS.put(html);
  return html;
}

/* The services ticker in the menu replaced each page's own "Marquee Top"
   strip, but the old strip stayed under it, so pages showed two tickers
   (owner, 2026-10-17). Remove a .marquee-strip that sits between the menu and
   the page's first section, with its label and the blank lines around it.
   A marquee further down a page (the homepage's) is content and stays. */
function dropOldTicker(html) {
  const end = html.indexOf(END);
  if (end === -1) return html;
  const after = end + END.length;
  const m = html.indexOf('<div class="marquee-strip"', after);
  // Only when nothing but blank lines and comments separates it from the menu.
  if (m === -1 || !/^(?:\s|<!--(?:(?!-->)[\s\S])*-->)*$/.test(html.slice(after, m))) return html;
  html = html.slice(0, after) + '\n' + html.slice(elementEnd(html, m)).replace(/^[ \t]*\n+/, '');
  // Its styles go with it, unless another marquee is still on the page.
  return html.includes('<div class="marquee-strip"') ? html : html.replace(/^[ \t]*(\.marquee-|@keyframes marquee-scroll)[^\n]*\}[ \t]*\n/gm, '');
}

function run(mode) {
  const nav = JSON.parse(fs.readFileSync(NAV, 'utf8'));
  const block = render(nav);
  const footer = renderFooter(nav);
  const drifted = [];
  /* The Design Studio's copy: same menu, absolute links. design.jtees.net
     fetches this file (jt-site-nav.php) and keeps a copy in its repo. */
  const snippetFile = path.join(PUBLIC, 'assets', 'data', 'site-nav.html');
  const snippet = render(nav, 'https://www.jtees.net') + '\n';
  if (!fs.existsSync(snippetFile) || fs.readFileSync(snippetFile, 'utf8') !== snippet) {
    drifted.push('assets/data/site-nav.html');
    if (mode === 'write') fs.writeFileSync(snippetFile, snippet);
  }
  /* And its copy of the footer. */
  const footFile = path.join(PUBLIC, 'assets', 'data', 'site-footer.html');
  const footSnippet = renderFooter(nav, 'https://www.jtees.net') + '\n';
  if (!fs.existsSync(footFile) || fs.readFileSync(footFile, 'utf8') !== footSnippet) {
    drifted.push('assets/data/site-footer.html');
    if (mode === 'write') fs.writeFileSync(footFile, footSnippet);
  }
  for (const rel of pages()) {
    const file = path.join(PUBLIC, rel);
    const before = fs.readFileSync(file, 'utf8');
    const after = applyReviews(applyFooter(apply(before, block), footer), rel);
    if (after !== before) {
      drifted.push(rel);
      if (mode === 'write') fs.writeFileSync(file, after);
    }
  }
  return drifted;
}

/* Menu, footer and review strip for one page, exactly as --write leaves it
   (tools/occasion-pages.js builds pages with this). */
function finish(html, rel) {
  const nav = JSON.parse(fs.readFileSync(NAV, 'utf8'));
  return applyReviews(applyFooter(apply(html, render(nav)), renderFooter(nav)), rel);
}

module.exports = { finish, render, renderFooter, apply, applyFooter, applyReviews, pages, run, START, END, FSTART, FEND, RS, NO_REVIEWS, CSS_V };

