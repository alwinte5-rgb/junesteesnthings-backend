/* Product cards, photos and reviews on the service, area and blog pages.
 *
 * Google Ads land on the service pages, and until 2026-10 those pages had no
 * photo but the logo, no product and no review above the very bottom
 * (owner: "the page was empty"). This script writes four blocks into every
 * page listed in public/assets/data/page-blocks.json, between markers, as
 * plain HTML: they show with no script and no feed, and Google reads them.
 *
 * Every page runs in one order (owner, 2026-10-17, after reading the
 * eye-tracking research: proof, the action and trust in the first screens,
 * the long copy for search below them):
 *
 *   hero          H1, pitch, the Google rating and the main photo
 *   our work      shop photos, straight after the hero
 *   products      "Design This" cards that open the Design Studio
 *   reviews       three Google reviews, the only reviews on the page; every
 *                 review is in the HTML and assets/js/pb-reviews.js picks
 *                 three at random, so pages and visits differ
 *   ...           the page's own copy, FAQ, call to action, related reading
 *
 * Blog pages have no hero: a gallery, when listed, then products and reviews
 * follow the article.
 *
 * assets/js/shop-feed.js refreshes the cards' photos and prices from the
 * Design Studio when it answers. A sticky "Design yours / Call" bar rides
 * along with the products block on phones.
 *
 *   node tools/page-blocks.js --write   rewrite every listed page
 *   node tools/page-blocks.js --check   list pages that have drifted (exit 1)
 *
 * tests/page-blocks.test.js runs --check.
 */

