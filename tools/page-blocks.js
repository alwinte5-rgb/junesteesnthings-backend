'use strict';

/* Product cards, photos and reviews on the service, area and blog pages.
 *
 * Google Ads land on the service pages, and until 2026-10 those pages had no
 * photo but the logo, no product and no review above the very bottom
 * (owner: "the page was empty"). This script writes four blocks into every
 * page listed in public/assets/data/page-blocks.json, between markers, as
 * plain HTML: they show with no script and no feed, and Google reads them.
 *
 *   hero photo    beside the page's H1 (service and area pages)
 *   products      "Design This" cards that open the Design Studio, right
 *                 after the opening section (blog: after the article)
 *   top reviews   three Google reviews from assets/data/reviews.json, under
 *                 the products; the strip above the footer stays
 *   our work      shop photos, above the FAQ (service and area pages)
 *
 * assets/js/shop-feed.js refreshes the cards' photos and prices from the
 * Design Studio when it answers. A sticky "Design yours / Call" bar rides
 * along with the products block on phones.
 *
 *   node tools/page-blocks.js --write   rewrite every listed page
 *   node tools/page-blocks.js --check   list pages that have drifted (exit 1)
 *
 * tests/page-blocks.test.js runs --check.
 */

const fs = require('node:fs');
const path = require('node:path');

const PUBLIC = path.join(__dirname, '..', 'public');
const DATA = path.join(PUBLIC, 'assets', 'data', 'page-blocks.json');
const REVIEWS = path.join(PUBLIC, 'assets', 'data', 'reviews.json');
// Hash-stamped (tools/lib/css-tag.js), like site-nav.css.
const BLOCKS_CSS = require('./lib/css-tag').cssTag('/assets/css/page-blocks.css');
const FEED_TAG = '<script src="/assets/js/shop-feed.js?v=20261017" defer></script>';
const PHONE = { tel: '+17739004592', display: '(773) 900-4592' };
const EMAIL = 'support@jtees.net';

const mark = (name) => [`<!-- ${name}:start — generated by tools/page-blocks.js from assets/data/page-blocks.json -->`, `<!-- ${name}:end -->`];
const BLOCKS = ['pb-hero', 'pb-products', 'pb-reviews', 'pb-work'];

const { escHtml: esc } = require('./lib/html-escape');

/* data-from names the page in GA4's designer_open event (analytics.js):
   services/embroidery.html -> svc_embroidery, blog/x.html -> blog_x. */
/* Every mention of the Design Studio is a link to it (owner, 2026-10-17:
   "make sure any mention of the designer takes you there"). */
const STUDIO = 'https://design.jtees.net/products.php';
const studioLink = (html, from) => html.replace(/Design Studio/, `<a href="${STUDIO}" data-from="${from}">Design Studio</a>`);

function fromTag(rel) {
  const [dir, file] = rel.split('/');
  const pre = { services: 'svc', areas: 'area', blog: 'blog' }[dir] || 'page';
  return `${pre}_${file.replace(/\.html$/, '').replace(/[^a-z0-9]+/gi, '_')}`;
}

function workImg(key) { return `/assets/images/work/${key}.jpg`; }

function heroBlock(data, page) {
  if (!page.hero) return '';
  const [s, e] = mark('pb-hero');
  return `${s}
<figure class="pb-hero-img"><img src="${workImg(page.hero)}" alt="${esc(data.work[page.hero])} by June's Tees &amp; Things, Chicago" width="560" height="420" loading="lazy" /></figure>
${e}`;
}

function card(item, from) {
  return `<a class="pb-card" href="${esc(item.link)}" data-from="${from}" data-card="service">
      <div class="pb-im"><img src="${esc(item.image)}" alt="Custom ${esc(item.name)} by June's Tees" loading="lazy" width="300" height="300" /></div>
      <div class="pb-bd"><div class="pb-nm">${esc(item.name)}</div><div class="pb-pr">${esc(item.price)}</div><span class="pb-go">Design This &rarr;</span></div>
    </a>`;
}

function productsBlock(data, page, rel) {
  const [s, e] = mark('pb-products');
  const from = fromTag(rel);
  const cards = page.products.map((id) => card(data.catalog[id], from)).join('\n    ');
  return `${s}
<section class="pb-products" aria-labelledby="pb-products-h">
  <div class="pb-wrap">
    <div class="pb-head">
      <div><div class="pb-tag"><a href="${STUDIO}" data-from="${from}">Design Studio</a> &middot; see it before you buy</div><h2 id="pb-products-h">${studioLink(esc(page.heading), from)}</h2></div>
      <a class="pb-all" href="${STUDIO}" data-from="${from}">All products &rarr;</a>
    </div>
    <div class="pb-grid">
    ${cards}
    </div>
    <p class="pb-note">Pick a product, add your text, photo or logo, and see the price as you go. Prefer help? <a href="/#contact">Send us your idea</a>, call <a href="tel:${PHONE.tel}">${PHONE.display}</a> or email <a href="mailto:${EMAIL}">${EMAIL}</a>.</p>
  </div>
</section>
<div class="pb-sticky" aria-label="Quick actions"><a href="${STUDIO}" class="pb-sticky-go" data-from="${from}_sticky">Design yours</a><a href="tel:${PHONE.tel}" class="pb-sticky-call" aria-label="Call ${PHONE.display}">📞</a></div>
${e}`;
}

function stars(n) { return '★★★★★'.slice(0, Math.round(n)); }

function reviewsBlock(reviews) {
  const [s, e] = mark('pb-reviews');
  const top = reviews.reviews.filter((r) => r.photo).slice(0, 3);
  const items = top.map((r) => `<figure class="pb-rv">
      <img src="${esc(r.photo)}" alt="" loading="lazy" width="320" height="220" />
      <figcaption><div class="pb-stars" aria-label="5 stars">★★★★★</div><b>${esc(r.title)}</b><p>${esc(r.text)}</p><span>${esc(r.who)}</span></figcaption>
    </figure>`).join('\n    ');
  return `${s}
<section class="pb-reviews" aria-labelledby="pb-reviews-h">
  <div class="pb-wrap">
    <div class="pb-head">
      <div><div class="pb-tag"><span class="pb-stars">${stars(reviews.rating)}</span> ${esc(reviews.rating)} on Google &middot; ${esc(reviews.count_on_google)} reviews</div><h2 id="pb-reviews-h">What Chicago customers say</h2></div>
      <a class="pb-all" href="${esc(reviews.google_url)}">All reviews &rarr;</a>
    </div>
    <div class="pb-rvs">
    ${items}
    </div>
  </div>
</section>
${e}`;
}

function workBlock(data, page) {
  if (!page.work || !page.work.length) return '';
  const [s, e] = mark('pb-work');
  const items = page.work.map((k) => `<figure><img src="${workImg(k)}" alt="${esc(data.work[k])}" loading="lazy" width="400" height="300" /><figcaption>${esc(data.work[k])}</figcaption></figure>`).join('\n    ');
  return `${s}
<section class="pb-work" aria-labelledby="pb-work-h">
  <div class="pb-wrap">
    <div class="pb-tag">Printed in our Lakeview shop</div>
    <h2 id="pb-work-h">Recent work</h2>
    <div class="pb-gallery">
    ${items}
    </div>
  </div>
</section>
${e}`;
}

/* Replace a marked block, or insert it at `at` the first time. */
function put(html, name, block, at) {
  const [s, e] = mark(name);
  const a = html.indexOf(s);
  if (a !== -1) {
    const z = html.indexOf(e, a);
    // A start marker without its end means a hand edit or a merge broke the
    // page; splicing anyway would paste the block over the wrong text.
    if (z === -1) throw new Error(`${name}: start marker without an end marker`);
    const b = z + e.length;
    // A block with nothing to show leaves no markers (and no blank line) behind.
    if (!block) return html.slice(0, a).replace(/\n$/, '') + html.slice(b);
    return html.slice(0, a) + block + html.slice(b);
  }
  if (!block) return html;
  const pos = at(html);
  if (pos === -1) throw new Error(`no place for ${name}`);
  return html.slice(0, pos) + block + '\n' + html.slice(pos);
}

/* The end of the element that opens at `from` (same tag, nesting counted). */
function elementEnd(html, from) {
  const tag = html.slice(from + 1).match(/^[a-zA-Z0-9]+/)[0].toLowerCase();
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
  re.lastIndex = from;
  let depth = 0, m;
  while ((m = re.exec(html))) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return m.index + m[0].length;
  }
  throw new Error(`unclosed <${tag}> at ${from}`);
}

const lineAfter = (html, i) => (i === -1 ? -1 : html.indexOf('\n', i) + 1);

/* Service and area pages: the hero's .container gets the photo as its last
   child; products follow the hero section; work goes before the FAQ section
   (or the call-to-action band when a page has no FAQ). Blog: products follow
   the article's </main>, or the post grid on the index. */
const where = {
  hero(html) {
    const h = html.indexOf('<section class="hero"');
    if (h === -1) return -1;
    const c = html.indexOf('<div class="container"', h);
    const end = elementEnd(html, c);
    return html.lastIndexOf('</div>', end - 1);
  },
  products(html) {
    const h = html.indexOf('<section class="hero"');
    if (h !== -1) return lineAfter(html, elementEnd(html, h) - 1);
    const m = html.indexOf('</main>');
    if (m !== -1) return lineAfter(html, m);
    const g = html.indexOf('<section class="blog-grid-section"');
    if (g !== -1) return lineAfter(html, elementEnd(html, g) - 1);
    return -1;
  },
  reviews(html) {
    const [, e] = mark('pb-products');
    return lineAfter(html, html.indexOf(e));
  },
  work(html) {
    const faq = html.search(/<section[^>]*>\s*<div class="container">\s*<div class="section-tag">[^<]*<\/div>\s*<h2>[^<]*(FAQ|Questions)/i);
    let at = faq !== -1 ? faq : html.indexOf('<section class="cta-band"');
    if (at === -1) at = html.indexOf('<!-- review-strip:start');
    if (at === -1) at = html.search(/<footer\b/i);
    return at === -1 ? -1 : html.lastIndexOf('\n', at) + 1;
  },
};

function apply(html, rel, data, reviews) {
  const page = data.pages[rel];
  html = put(html, 'pb-hero', heroBlock(data, page), where.hero);
  html = put(html, 'pb-products', productsBlock(data, page, rel), where.products);
  html = put(html, 'pb-reviews', reviewsBlock(reviews), where.reviews);
  html = put(html, 'pb-work', workBlock(data, page), where.work);
  html = BLOCKS_CSS.put(html);
  if (!html.includes('/assets/js/shop-feed.js')) html = html.replace('</body>', `${FEED_TAG}\n</body>`);
  return html;
}

function load() {
  return {
    data: JSON.parse(fs.readFileSync(DATA, 'utf8')),
    reviews: JSON.parse(fs.readFileSync(REVIEWS, 'utf8')),
  };
}

/* Every id, link and photo in the data file must be real before any page is
   written: a typo would otherwise print a card with no photo or no link. */
function validate(data) {
  const bad = [];
  for (const [id, c] of Object.entries(data.catalog)) {
    let u;
    try { u = new URL(c.link); } catch { bad.push(`${id}: bad link`); continue; }
    if (u.protocol !== 'https:' || u.host !== 'design.jtees.net') bad.push(`${id}: link leaves the Design Studio`);
    if (!c.name || !c.price) bad.push(`${id}: missing name or price`);
    if (!fs.existsSync(path.join(PUBLIC, c.image))) bad.push(`${id}: no photo at ${c.image}`);
  }
  for (const k of Object.keys(data.work)) if (!fs.existsSync(path.join(PUBLIC, workImg(k)))) bad.push(`work photo missing: ${k}`);
  for (const [rel, p] of Object.entries(data.pages)) {
    if (!fs.existsSync(path.join(PUBLIC, rel))) bad.push(`${rel}: no such page`);
    for (const id of p.products || []) if (!data.catalog[id]) bad.push(`${rel}: unknown product ${id}`);
    for (const k of [p.hero, ...(p.work || [])].filter(Boolean)) if (!data.work[k]) bad.push(`${rel}: unknown work photo ${k}`);
    if (!p.heading || !(p.products || []).length) bad.push(`${rel}: needs a heading and products`);
  }
  return bad;
}

function run(mode) {
  const { data, reviews } = load();
  const bad = validate(data);
  if (bad.length) throw new Error('page-blocks.json:\n  ' + bad.join('\n  '));
  const drifted = [];
  for (const rel of Object.keys(data.pages)) {
    const file = path.join(PUBLIC, rel);
    const before = fs.readFileSync(file, 'utf8');
    const after = apply(before, rel, data, reviews);
    if (after !== before) {
      drifted.push(rel);
      if (mode === 'write') fs.writeFileSync(file, after);
    }
  }
  return drifted;
}

module.exports = { apply, load, validate, run, mark, BLOCKS, fromTag };

if (require.main === module) {
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  const changed = run(mode);
  if (mode === 'write') console.log(`page blocks written into ${changed.length} page(s)`);
  else if (changed.length) { console.log('page blocks out of date on:\n  ' + changed.join('\n  ') + '\nrun: node tools/page-blocks.js --write'); process.exit(1); }
  else console.log('every page has the current blocks');
}
